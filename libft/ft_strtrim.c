#include "libft.h"

static int	is_in_set(char c, char const *set)
{
	while (*set)
	{
		if (c == *set)
		{
			return (1);
		}
		set++;
	}
	return (0);
}

char	*ft_strtrim(char const *s1, char const *set)
{
	size_t	start;
	size_t	end;

	if (!s1)
		return (NULL);
	if (!set)
		return (ft_strdup(s1));
	start = 0;
	end = ft_strlen(s1);
	while (is_in_set(s1[start], set) && s1[start])
		start++;
	if (start == end)
		return (ft_strdup(""));
	while (is_in_set(s1[end - 1], set) && end > start)
		end--;
	return (ft_substr(s1, start, end - start));
}
